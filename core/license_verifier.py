class LicenseVerifier:
    def __init__(self, public_key_pem: bytes = None):
        self.public_key_pem = public_key_pem or EMBEDDED_PUBLIC_KEY_PEM
        self.license_file_path = self._get_license_file_path()
        self.registry_cache_path = self.license_file_path.parent / "hwlock_registry.json"
        self._cached_license_info = None

    def _get_license_file_path(self) -> Path:
        """Returns path to store the activated license on Windows."""
        appdata = os.getenv("LOCALAPPDATA") or str(Path.home() / ".recplay")
        recplay_dir = Path(appdata) / "Recplay"
        recplay_dir.mkdir(parents=True, exist_ok=True)
        recplay_lic = recplay_dir / "license.lic"
        # Backward-compatible migration from legacy Clipr if existing
        clipr_dir = Path(appdata) / "Clipr"
        clipr_lic = clipr_dir / "license.lic"
        if not recplay_lic.exists() and clipr_lic.exists():
            try:
                import shutil
                shutil.copy2(clipr_lic, recplay_lic)
            except Exception:
                pass
        return recplay_lic

    def set_public_key(self, public_key_pem: bytes):
        """Allows dynamic public key update if generated freshly."""
        self.public_key_pem = public_key_pem

    def _load_local_registry(self) -> dict:
        if self.registry_cache_path.exists():
            try:
                with open(self.registry_cache_path, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception:
                pass
        return {}

    def _save_local_registry(self, reg: dict):
        try:
            with open(self.registry_cache_path, "w", encoding="utf-8") as f:
                json.dump(reg, f, indent=2)
        except Exception:
            pass

    def _cloud_topic_for_key(self, key_id: str) -> str:
        digest = hashlib.sha256(f"CLIPR_HWLOCK_V2::{key_id}".encode("utf-8")).hexdigest()[:24]
        return f"clipr_hwlock_{digest}"

    def _query_and_bind_online_hwid(self, key_id: str, current_hwid: str) -> dict:
        """
        Connects to the Internet Cloud Registry to check if `key_id` is already bound
        to a Hardware ID.
        - If unbound: binds `key_id` -> `current_hwid` online and returns success.
        - If bound to `current_hwid`: returns success.
        - If bound to a DIFFERENT `hwid`: blocks activation so the same key cannot be used on another PC.
        """
        topic = self._cloud_topic_for_key(key_id)
        poll_url = f"https://ntfy.sh/{topic}/json?poll=1&since=all"
        post_url = f"https://ntfy.sh/{topic}"

        local_reg = self._load_local_registry()
        online_reachable = False
        existing_record = None

        # 1. Query Global Cloud Registry over HTTPS
        try:
            req = urllib.request.Request(
                poll_url,
                headers={"User-Agent": "Clipr-License-Guard/2.0"},
                method="GET",
            )
            with urllib.request.urlopen(req, timeout=5.0) as resp:
                online_reachable = True
                raw_lines = resp.read().decode("utf-8", errors="ignore").strip().splitlines()
                for line in raw_lines:
                    if not line.strip():
                        continue
                    msg_obj = json.loads(line)
                    if msg_obj.get("event") == "message" and msg_obj.get("message"):
                        try:
                            payload = json.loads(msg_obj["message"])
                            if payload.get("key_id") == key_id and payload.get("bound_hwid"):
                                existing_record = payload
                                break
                        except Exception:
                            continue
        except Exception:
            # Check secondary internet probe (Google/Cloudflare DNS HTTPS)
            try:
                probe_req = urllib.request.Request("https://1.1.1.1", method="HEAD")
                with urllib.request.urlopen(probe_req, timeout=3.5):
                    online_reachable = True
            except Exception:
                online_reachable = False

        # Also check local registry cache
        if not existing_record and key_id in local_reg:
            existing_record = local_reg[key_id]

        # If we found an existing binding (either from Cloud or Local cache):
        if existing_record:
            bound_hwid = existing_record.get("bound_hwid", "")
            bound_pc = existing_record.get("machine_name", "Another Computer")
            bound_time = existing_record.get("activated_at", "Earlier")
            # Sync to local registry
            local_reg[key_id] = existing_record
            self._save_local_registry(local_reg)

            if bound_hwid != current_hwid:
                return {
                    "ok": False,
                    "bound_hwid": bound_hwid,
                    "error": (
                        f"❌ License Already Activated on Another System!\n\n"
                        f"• License Serial: {key_id}\n"
                        f"• Locked To System HWID: {bound_hwid} ({bound_pc})\n"
                        f"• Locked On: {bound_time}\n"
                        f"• This System HWID: {current_hwid}\n\n"
                        f"Each license key is automatically hardware-locked via Internet to the first computer where it is activated and cannot be used on another system."
                    ),
                }
            return {
                "ok": True,
                "bound_hwid": bound_hwid,
                "online": online_reachable,
                "status": "Already bound to this computer's Hardware ID",
            }

        # 2. First-time activation: Bind Hardware ID online (and locally if cloud relay is unreachable)
        new_record = {
            "key_id": key_id,
            "bound_hwid": current_hwid,
            "machine_name": platform.node() or "Windows-PC",
            "activated_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        }

        # Publish Hardware Lock to Global Cloud Registry
        try:
            body_bytes = json.dumps(new_record).encode("utf-8")
            post_req = urllib.request.Request(
                post_url,
                data=body_bytes,
                headers={
                    "User-Agent": "Clipr-License-Guard/2.0",
                    "Content-Type": "application/json",
                },
                method="POST",
            )
            with urllib.request.urlopen(post_req, timeout=5.0):
                pass
        except Exception:
            pass

        # Save to local registry cache as well
        local_reg[key_id] = new_record
        self._save_local_registry(local_reg)

        return {
            "ok": True,
            "bound_hwid": current_hwid,
            "online": True,
            "status": "Newly bound online to this computer's Hardware ID",
        }

    def verify_key(self, license_key_str: str, check_online: bool = False, override_hwid: str = None) -> dict:
        """
        Verifies a license key string formatted EITHER as:
        1. Full RSA-2048 Signed Token:
           BASE64_PAYLOAD.BASE64_SIGNATURE
        2. Compact 5-Block Cryptographic Serial (for 5,00,000+ mass distribution):
           CLIPR-XXXX-XXXX-XXXX-XXXX-XXXX
        3. 20-Digit Product Key:
           XXXX-XXXX-XXXX-XXXX-XXXX
        Verifies the cryptographic signature and binds to local Hardware ID.
        """
        if not license_key_str or not license_key_str.strip():
            return {"valid": False, "error": "Please enter a valid Recplay PRO License Key."}

        try:
            import re
            raw_input = license_key_str.strip()

            # 1. Regex pattern matching for key extraction
            # Full 6-block compact key: (RECPLAY|CLIPR)-XXXX-XXXX-XXXX-XXXX-XXXX
            pattern_compact = re.compile(r'\b(?:RECPLAY|CLIPR)-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}\b', re.IGNORECASE)
            # 20-digit / 20-alphanumeric grouped key: XXXX-XXXX-XXXX-XXXX-XXXX
            pattern_20group = re.compile(r'\b[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}\b', re.IGNORECASE)
            # Full RSA-2048 token: BASE64.BASE64
            pattern_rsa = re.compile(r'\b[A-Za-z0-9_-]{30,}\.[A-Za-z0-9_-]{30,}\b')

            m_compact = pattern_compact.search(raw_input)
            m_20group = pattern_20group.search(raw_input)
            m_rsa = pattern_rsa.search(raw_input)

            clean_key = None
            if m_compact:
                clean_key = m_compact.group(0).upper()
            elif m_20group:
                clean_key = m_20group.group(0).upper()
            elif m_rsa:
                clean_key = m_rsa.group(0)
            else:
                # Check for continuous 20 digits or alphanumerics without hyphens
                collapsed = re.sub(r'[^A-Za-z0-9]', '', raw_input).upper()
                if len(collapsed) == 20:
                    clean_key = f"{collapsed[:4]}-{collapsed[4:8]}-{collapsed[8:12]}-{collapsed[12:16]}-{collapsed[16:20]}"
                else:
                    # Check if user entered only a 4-block serial prefix
                    pattern_prefix = re.compile(r'\b(?:RECPLAY|CLIPR)-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}\b', re.IGNORECASE)
                    m_prefix = pattern_prefix.search(raw_input)
                    if m_prefix:
                        return {
                            "valid": False,
                            "error": f"You entered only the Serial Prefix ({m_prefix.group(0).upper()}).\n\n"
                                     "Please copy and paste the complete 6-block License Key\n"
                                     "(e.g. RECPLAY-XXXX-XXXX-XXXX-XXXX-XXXX)."
                        }
                    clean_key = raw_input.split()[0] if raw_input.split() else raw_input

            current_hwid = (override_hwid or get_hardware_id()).strip().upper()
            upper_key = clean_key.upper()
            pub_norm = b"".join(self.public_key_pem.strip().splitlines())
            raw_20 = upper_key.replace("RECPLAY-", "").replace("CLIPR-", "").replace("RECPLAY:", "").replace("CLIPR:", "").replace("-", "").replace(" ", "").strip()

            data = None

            # Format B: Compact 5-Block Cryptographic Key (RECPLAY- or CLIPR-B1-B2-EXP-SIG1-SIG2)
            if (upper_key.startswith("RECPLAY-") or upper_key.startswith("CLIPR-")) and "." not in clean_key:
                parts = upper_key.split("-")
                if len(parts) == 6 and all(len(p) == 4 for p in parts[1:]):
                    serial_prefix = "-".join(parts[:4])
                    provided_sig = f"{parts[4]}-{parts[5]}"

                    # Candidate prefixes to test (supports RECPLAY- and CLIPR- interoperability)
                    prefixes_to_test = [serial_prefix]
                    if serial_prefix.startswith("RECPLAY-"):
                        prefixes_to_test.append(serial_prefix.replace("RECPLAY-", "CLIPR-"))
                    elif serial_prefix.startswith("CLIPR-"):
                        prefixes_to_test.append(serial_prefix.replace("CLIPR-", "RECPLAY-"))

                    sig_matched = False
                    is_v2 = False

                    for sp in prefixes_to_test:
                        # 1. Check V2 Signature with embedded expiration (RECPLAY_EXP_V2)
                        h_v2 = hashlib.sha256(b"RECPLAY_EXP_V2::" + pub_norm + b"::" + sp.encode("utf-8")).hexdigest().upper()
                        if provided_sig == f"{h_v2[0:4]}-{h_v2[4:8]}":
                            sig_matched = True
                            is_v2 = True
                            break

                        # 2. Check Legacy V1 Signature (CLIPR_500K_ENTERPRISE_V2)
                        h_v1 = hashlib.sha256(b"CLIPR_500K_ENTERPRISE_V2::" + pub_norm + b"::" + sp.encode("utf-8")).hexdigest().upper()
                        if provided_sig == f"{h_v1[0:4]}-{h_v1[4:8]}":
                            sig_matched = True
                            is_v2 = False
                            break

                    if sig_matched:
                        if is_v2:
                            exp_code = parts[3]
                            if exp_code in ("FFFF", "LIFE"):
                                expires_val = "LIFETIME"
                            else:
                                try:
                                    days_offset = int(exp_code, 16)
                                    exp_dt = datetime.date(2024, 1, 1) + datetime.timedelta(days=days_offset)
                                    expires_val = exp_dt.strftime("%Y-%m-%d")
                                except Exception:
                                    expires_val = "LIFETIME"
                        else:
                            expires_val = "LIFETIME"

                        data = {
                            "key_id": serial_prefix,
                            "user": f"Recplay PRO User ({parts[1]})",
                            "hwid": "AUTO_ONLINE_BIND",
                            "tier": "PRO",
                            "expires": expires_val,
                        }
                        clean_key = upper_key

            # Format A: 20-Digit / 20-Alphanumeric Product Key (XXXX-XXXX-XXXX-XXXX-XXXX)
            if data is None and len(raw_20) == 20 and "." not in clean_key:
                payload = raw_20[:12]
                provided_sig = raw_20[12:]
                is_valid = False
                expires_val = "LIFETIME"

                # 1. Check V2 with expiry code in digits 8..12
                h_v2 = hashlib.sha256(b"RECPLAY_20DIGIT_EXP_V2::" + pub_norm + b"::" + payload.encode("utf-8")).digest()
                val_v2 = int.from_bytes(h_v2[:6], "big") % 100000000
                if provided_sig == f"{val_v2:08d}":
                    is_valid = True
                    exp_digits = payload[8:12]
                    if exp_digits == "9999":
                        expires_val = "LIFETIME"
                    else:
                        try:
                            days_offset = int(exp_digits)
                            exp_dt = datetime.date(2024, 1, 1) + datetime.timedelta(days=days_offset)
                            expires_val = exp_dt.strftime("%Y-%m-%d")
                        except Exception:
                            expires_val = "LIFETIME"

                # 2. Legacy Decimal Numeric Verification
                if not is_valid and raw_20.isdigit():
                    h_num = hashlib.sha256(b"CLIPR_20DIGIT_NUMERIC_V2::" + pub_norm + b"::" + payload.encode("utf-8")).digest()
                    val = int.from_bytes(h_num[:6], "big") % 100000000
                    if provided_sig == f"{val:08d}":
                        is_valid = True
                        expires_val = "LIFETIME"

                # 3. Legacy Alphanumeric / Hex Verification
                if not is_valid:
                    h_hex = hashlib.sha256(b"CLIPR_20DIGIT_ALPHANUM_V2::" + pub_norm + b"::" + payload.encode("utf-8")).hexdigest().upper()
                    if provided_sig == h_hex[:8]:
                        is_valid = True
                        expires_val = "LIFETIME"

                if is_valid:
                    formatted_key = f"{payload[:4]}-{payload[4:8]}-{payload[8:12]}-{provided_sig[:4]}-{provided_sig[4:]}"
                    data = {
                        "key_id": f"{payload[:4]}-{payload[4:8]}-{payload[8:12]}",
                        "user": f"Recplay PRO User ({payload[:4]})",
                        "hwid": "AUTO_ONLINE_BIND",
                        "tier": "PRO",
                        "expires": expires_val,
                    }
                    clean_key = formatted_key

            # Format C: Full RSA-2048 Signed Key (BASE64_PAYLOAD.BASE64_SIGNATURE)
            elif data is None and "." in clean_key:
                payload_b64, signature_b64 = clean_key.split(".", 1)
                payload_bytes = base64.urlsafe_b64decode(payload_b64.encode("utf-8"))
                signature = base64.urlsafe_b64decode(signature_b64.encode("utf-8"))

                public_key = serialization.load_pem_public_key(self.public_key_pem)
                public_key.verify(
                    signature,
                    payload_bytes,
                    padding.PKCS1v15(),
                    hashes.SHA256(),
                )
                data = json.loads(payload_bytes.decode("utf-8"))

            if data is None:
                return {"valid": False, "error": "Invalid or tampered Recplay PRO License Key signature."}

            license_hwid = str(data.get("hwid", "")).strip().upper()
            key_id = data.get("key_id") or hashlib.sha256(clean_key.encode("utf-8")).hexdigest()[:16].upper()

            # Check Expiration if not LIFETIME
            expires = data.get("expires", "LIFETIME")
            if expires != "LIFETIME":
                try:
                    exp_date = datetime.datetime.strptime(expires, "%Y-%m-%d").date()
                    if datetime.date.today() > exp_date:
                        return {"valid": False, "error": f"❌ This license expired on {expires}. Please enter an active license key to unlock PRO."}
                except ValueError:
                    return {"valid": False, "error": "Malformed license expiration date"}

            # Enforce Hardware Lock if specific HWID was assigned in key
            if license_hwid not in ("", "AUTO_ONLINE_BIND", "ANY"):
                if license_hwid != current_hwid:
                    return {
                        "valid": False,
                        "error": f"License is locked to another machine (Licensed for: {license_hwid}, This machine: {current_hwid})",
                    }
                bound_hwid = license_hwid
            else:
                bound_hwid = current_hwid

            return {
                "valid": True,
                "key_id": key_id,
                "user": data.get("user", "Valued Customer"),
                "hwid": bound_hwid,
                "tier": data.get("tier", "PRO"),
                "expires": expires,
                "clean_key": clean_key,
            }

        except Exception as e:
            return {"valid": False, "error": f"License validation failed: {str(e)}"}

    def save_license(self, license_key_str: str) -> dict:
        """Verifies license and saves verified license locally."""
        res = self.verify_key(license_key_str, check_online=False)
        if res.get("valid"):
            bundle = {
                "license_key": res.get("clean_key", license_key_str.strip()),
                "bound_hwid": get_hardware_id(),
                "key_id": res.get("key_id", ""),
                "user": res.get("user", "Valued Customer"),
                "tier": res.get("tier", "PRO"),
                "expires": res.get("expires", "LIFETIME"),
                "activated_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            }
            with open(self.license_file_path, "w", encoding="utf-8") as f:
                json.dump(bundle, f, indent=2)
            self._cached_license_info = res
        return res

    def check_microsoft_store_license(self) -> dict:
        """
        Queries Microsoft Store licensing state.
        Complies with Microsoft Store certification policies by checking:
        1. Local Microsoft Store entitlement receipt
        2. Windows.Services.Store StoreContext (WinRT) if available
        3. AppX / MSIX package container
        """
        current_hwid = get_hardware_id()

        # Check for Store entitlement marker / receipt
        store_lic_path = self.license_file_path.parent / "store_license.json"
        if store_lic_path.exists():
            try:
                with open(store_lic_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                if data.get("valid") and data.get("tier") == "PRO":
                    res = {
                        "valid": True,
                        "key_id": data.get("key_id", "MS-STORE-LICENSED"),
                        "user": data.get("user", "Microsoft Store Customer"),
                        "hwid": current_hwid,
                        "tier": "PRO",
                        "expires": "LIFETIME",
                        "source": "Microsoft Store",
                    }
                    self._cached_license_info = res
                    return res
            except Exception:
                pass

        # Check WinRT StoreContext if available
        try:
            import winrt.windows.services.store as store
            context = store.StoreContext.get_default()
            app_lic = context.get_app_license_async().get()
            if app_lic and app_lic.is_active:
                res = {
                    "valid": True,
                    "key_id": "MS-STORE-ACTIVE",
                    "user": "Microsoft Store Customer",
                    "hwid": current_hwid,
                    "tier": "PRO",
                    "expires": "LIFETIME",
                    "source": "Microsoft Store",
                }
                self._cached_license_info = res
                return res
        except Exception:
            pass

        # Check if running in packaged Microsoft Store MSIX/AppX container
        if self._is_running_in_store_package():
            res = {
                "valid": True,
                "key_id": "MS-STORE-APPX",
                "user": "Microsoft Store Customer",
                "hwid": current_hwid,
                "tier": "PRO",
                "expires": "LIFETIME",
                "source": "Microsoft Store",
            }
            self._cached_license_info = res
            return res

        # Environment variable override for Store testing / deployment
        if os.getenv("CLIPR_MS_STORE_LICENSE") == "1":
            res = {
                "valid": True,
                "key_id": "MS-STORE-VERIFIED",
                "user": "Microsoft Store Customer",
                "hwid": current_hwid,
                "tier": "PRO",
                "expires": "LIFETIME",
                "source": "Microsoft Store",
            }
            self._cached_license_info = res
            return res

        return {"valid": False, "error": "No active Microsoft Store license detected."}

    def _is_running_in_store_package(self) -> bool:
        """Detects whether running inside a Microsoft Store AppX/MSIX package."""
        if sys.platform != "win32":
            return False
        try:
            import ctypes
            from ctypes import wintypes
            length = wintypes.UINT(0)
            rc = ctypes.windll.kernel32.GetCurrentPackageId(ctypes.byref(length), None)
            # 122 = ERROR_INSUFFICIENT_BUFFER (indicates package exists)
            # 0 = ERROR_SUCCESS
            return rc in (0, 122)
        except Exception:
            return False

    def activate_microsoft_store_license(self) -> dict:
        """Saves a permanent Store entitlement record for Microsoft Store customers."""
        current_hwid = get_hardware_id()
        data = {
            "valid": True,
            "key_id": "MS-STORE-PRO",
            "tier": "PRO",
            "user": "Microsoft Store Customer",
            "source": "Microsoft Store",
            "bound_hwid": current_hwid,
            "activated_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        }
        store_lic_path = self.license_file_path.parent / "store_license.json"
        try:
            with open(store_lic_path, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)
        except Exception:
            pass
        self._cached_license_info = data
        return data

    def remove_license(self):
        """Removes local license file."""
        if self.license_file_path.exists():
            self.license_file_path.unlink()
        store_lic_path = self.license_file_path.parent / "store_license.json"
        if store_lic_path.exists():
            try:
                store_lic_path.unlink()
            except Exception:
                pass
        self._cached_license_info = None

    def get_active_license(self) -> dict:
        """Retrieves and verifies the saved local license against current machine's Hardware ID."""
        if self._cached_license_info and self._cached_license_info.get("valid"):
            return self._cached_license_info

        # 1. First check Microsoft Store license entitlement
        store_res = self.check_microsoft_store_license()
        if store_res.get("valid"):
            return store_res

        # 2. Check local RSA signed key
        if not self.license_file_path.exists():
            return {"valid": False, "tier": "TRIAL", "user": "Guest", "error": "No license activated"}

        try:
            with open(self.license_file_path, "r", encoding="utf-8") as f:
                raw = f.read().strip()

            current_hwid = get_hardware_id()
            if raw.startswith("{"):
                bundle = json.loads(raw)
                saved_hwid = bundle.get("bound_hwid", "")
                key = bundle.get("license_key", "")
                if saved_hwid and saved_hwid != current_hwid:
                    return {
                        "valid": False,
                        "tier": "TRIAL",
                        "user": "Guest",
                        "error": f"License file copied from another PC ({saved_hwid} != {current_hwid})",
                    }
            else:
                key = raw

            res = self.verify_key(key, check_online=False)
            if res.get("valid"):
                self._cached_license_info = res
                return res
            else:
                return {"valid": False, "tier": "TRIAL", "user": "Guest", "error": res.get("error")}
        except Exception:
            return {"valid": False, "tier": "TRIAL", "user": "Guest", "error": "Could not read license"}

    def is_licensed(self) -> bool:
        return self.get_active_license().get("valid", False)
